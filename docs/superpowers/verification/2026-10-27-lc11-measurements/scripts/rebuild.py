#!/usr/bin/env python3
"""Simulated `register.py rebuild --specs <root> --slug <slug>`: regenerates register.json and
register.md from security/<slug>/runs/*.json alone, in (seq, at, file name) order, deterministically.
Like the real one it needs no git and never reads the derived files back."""
import json, os, sys

root, slug = sys.argv[1], sys.argv[2]
d = os.path.join(root, "security", slug)
runs = os.path.join(d, "runs")
recs = []
for n in sorted(os.listdir(runs)) if os.path.isdir(runs) else []:
    if n.endswith(".json"):
        with open(os.path.join(runs, n), encoding="utf-8") as fh:
            r = json.load(fh)  # raises on a conflicted (marker-laden) record, as the real one exits 2
        r["_file"] = n
        recs.append(r)
recs.sort(key=lambda r: (r["seq"], r["at"], r["_file"]))
findings = {}
for r in recs:
    for f in r.get("findings", []):
        findings[f["origin"]] = {"title": f["title"], "status": f["status"], "by": r["_file"]}
n = 0
numbered = []
for origin in sorted(findings, key=lambda o: [x["_file"] for x in recs if any(f["origin"] == o for f in x.get("findings", []))][0]):
    n += 1
    numbered.append(("SEC#%d" % n, origin, findings[origin]))
state = {"runs": [r["_file"] for r in recs], "last_at": recs[-1]["at"] if recs else None,
         "findings": [{"id": i, "origin": o, **f} for i, o, f in numbered]}
with open(os.path.join(d, "register.json"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write(json.dumps(state, indent=2, sort_keys=True) + "\n")
lines = ["<!-- Generated by rebuild.py from runs/. Never edit it by hand. -->", "",
         "# Security register: %s" % slug, "", "Runs: %d, last at %s" % (len(recs), state["last_at"]), "",
         "| ID | Origin | Status | Title |", "|---|---|---|---|"]
lines += ["| [%s] | %s | %s | %s |" % (i, o, f["status"], f["title"]) for i, o, f in numbered]
with open(os.path.join(d, "register.md"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines) + "\n")
print(json.dumps({"rebuilt": slug, "runs": len(recs), "findings": len(numbered)}))
